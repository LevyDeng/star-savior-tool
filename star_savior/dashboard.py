"""Settings composition based on the generated blue-white reference board."""
from PySide6.QtCore import Qt
from PySide6.QtWidgets import QFrame, QHBoxLayout, QLabel, QScrollArea, QVBoxLayout, QWidget


def build_dashboard(window):
    # Retain the working controls and connections while replacing their old containers.
    keys = {'sync_button': 'sync', 'network_button': 'network_settings', 'select_region': 'regions',
            'release_button': 'release_models', 'auto_release_models': 'auto_release_models', 'start_button': 'start'}
    window.translatable = [(getattr(window, name), key) for name, key in keys.items()]
    body = QWidget()
    body.setObjectName('settingsBody')
    root = QVBoxLayout(body)
    root.setContentsMargins(26, 22, 26, 22)
    root.setSpacing(16)
    heading = window.label('journey_helper')
    heading.setObjectName('pageHeading')
    root.addWidget(heading)
    subtitle = window.label('helper_subtitle')
    subtitle.setObjectName('muted')
    root.addWidget(subtitle)
    columns = QHBoxLayout()
    columns.setSpacing(16)
    left = QVBoxLayout()
    left.setSpacing(16)

    def card(key):
        panel = QFrame()
        panel.setObjectName('settingsCard')
        layout = QVBoxLayout(panel)
        layout.setContentsMargins(20, 18, 20, 18)
        layout.setSpacing(12)
        title = window.label(key)
        title.setObjectName('sectionHeading')
        layout.addWidget(title)
        return panel, layout

    database, data = card('guide_data')
    source = QHBoxLayout()
    source.addWidget(window.label('guide_source'))
    source.addWidget(window.source_list, 1)
    data.addLayout(source)
    window.summary.setWordWrap(True)
    data.addWidget(window.summary)
    separate = window.label('sources_separate')
    separate.setObjectName('muted')
    separate.setWordWrap(True)
    data.addWidget(separate)
    actions = QHBoxLayout()
    actions.addWidget(window.sync_button, 1)
    actions.addWidget(window.button('website', window.open_source), 1)
    data.addLayout(actions)
    left.addWidget(database)
    recognition, controls = card('recognition_settings')
    controls.addWidget(window.window_list)
    actions = QHBoxLayout()
    actions.addWidget(window.button('refresh', window.refresh_windows), 1)
    actions.addWidget(window.select_region, 1)
    controls.addLayout(actions)
    difficulty = QHBoxLayout()
    difficulty.addWidget(window.label('difficulty'))
    difficulty.addWidget(window.difficulty_list, 1)
    controls.addLayout(difficulty)
    left.addWidget(recognition)
    left.addStretch(1)
    columns.addLayout(left, 3)
    appearance, controls = card('floating_settings')
    appearance.setMinimumWidth(290)
    preview = window.label('floating_preview')
    preview.setObjectName('muted')
    preview.setAlignment(Qt.AlignmentFlag.AlignCenter)
    controls.addWidget(preview)
    controls.addWidget(window.button_preview, 0, Qt.AlignmentFlag.AlignHCenter)
    controls.addSpacing(8)
    for key, slider, value in [('floating_size', window.button_size, window.button_size_value),
                               ('floating_transparency', window.button_transparency, window.button_transparency_value)]:
        row = QHBoxLayout()
        label = window.label(key)
        label.setWordWrap(True)
        row.addWidget(label, 1)
        row.addWidget(value)
        controls.addLayout(row)
        controls.addWidget(slider)
    controls.addStretch(1)
    columns.addWidget(appearance, 2)
    root.addLayout(columns, 1)
    # Keep the launch controls reachable on laptops with a small logical screen height.
    shell = QWidget()
    outer = QVBoxLayout(shell)
    outer.setContentsMargins(26, 18, 26, 18)
    outer.setSpacing(14)
    root.setContentsMargins(0, 0, 0, 0)
    scroll = QScrollArea()
    scroll.setFrameShape(QFrame.Shape.NoFrame)
    scroll.setWidgetResizable(True)
    scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
    scroll.setWidget(body)
    outer.addWidget(scroll, 1)
    outer.addWidget(window.status)
    footer = QHBoxLayout()
    utilities = QVBoxLayout()
    actions = QHBoxLayout()
    actions.addWidget(window.network_button)
    actions.addWidget(window.release_button)
    actions.addStretch(1)
    utilities.addLayout(actions)
    utilities.addWidget(window.auto_release_models)
    footer.addLayout(utilities, 1)
    footer.addWidget(window.start_button)
    outer.addLayout(footer)
    window.setCentralWidget(shell)
    window.resize(980, 730)

